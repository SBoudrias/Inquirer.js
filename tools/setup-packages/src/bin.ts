#!/usr/bin/env node
import { setupPackages } from './index.ts';

const check = process.argv.includes('--check');

try {
  const drift = await setupPackages({ check });

  if (check) {
    if (drift.length > 0) {
      for (const file of drift) {
        console.error(`[would fix] ${file}.`);
      }
      console.error(
        `[would fix] ${drift.length} file${drift.length === 1 ? '' : 's'} need${drift.length === 1 ? 's' : ''} to be regenerated by \`yarn setup\`.`,
      );
      process.exitCode = 1;
    } else {
      console.log('All workspace setup files are up to date.');
    }
  }
} catch (error: unknown) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
